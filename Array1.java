public class Array1 {
    
    public static void main(String[] args) {
        // Declaration and allocation
        int[] marks = new int[5];

        // Placement statements
        marks[0] = 65;
        marks[1] = 72;
        marks[2] = 58;
        marks[3] = 81;
        marks[4] = 90;

        // Displaying first, third, and last values
        System.out.println("First value: " + marks[0]);
        System.out.println("Third value: " + marks[2]);
        System.out.println("Last value:  " + marks[4]);
    }
}
